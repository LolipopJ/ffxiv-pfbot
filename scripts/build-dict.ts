export interface DictSourceConfig {
  fileName: string;
  column: string;
  // Filters receive the lowercase English dictionary key.
  filter?: (key: string) => boolean;
}

export interface DictSource extends DictSourceConfig {
  englishCsv: string;
  chineseCsv: string;
}

