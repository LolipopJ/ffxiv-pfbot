function parseCsv(csv: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;

  // Quoted fields may contain commas, newlines, and escaped double quotes.
  csv = csv.replace(/^\uFEFF/, "");
  for (let index = 0; index < csv.length; index++) {
    const character = csv[index];
    if (character === '"') {
      if (quoted && csv[index + 1] === '"') {
        field += '"';
        index++;
      } else {
        quoted = !quoted;
      }
    } else if (!quoted && character === ",") {
      row.push(field);
      field = "";
    } else if (!quoted && (character === "\n" || character === "\r")) {
      row.push(field);
      if (row.some((value) => value !== "")) rows.push(row);
      row = [];
      field = "";
      if (character === "\r" && csv[index + 1] === "\n") index++;
    } else {
      field += character;
    }
  }

  if (quoted) throw new Error("Unterminated quoted CSV field.");
  if (row.length > 0 || field !== "") {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

function readTexts(
  csv: string,
  column: string,
  fileName: string,
): Map<string, string> {
  const rows = parseCsv(csv);
  const keyIndex = rows[0]?.indexOf("key") ?? -1;
  const textIndex = rows[0]?.indexOf(column) ?? -1;
  if (keyIndex < 0 || textIndex < 0) {
    throw new Error(`${fileName} must contain columns "key" and "${column}".`);
  }

  const texts = new Map<string, string>();
  // Skip column numbers, column names, offsets, and types.
  for (const row of rows.slice(4)) {
    const key = row[keyIndex];
    const text = row[textIndex];
    if (key === undefined || text === undefined) {
      throw new Error(`Incomplete ${fileName} row.`);
    }
    texts.set(key, text);
  }
  return texts;
}

export function buildDict(
  sources: readonly DictSource[],
): Record<string, string> {
  const entries: [string, string][] = [];

  for (const { fileName, column, englishCsv, chineseCsv, filter } of sources) {
    const englishTexts = readTexts(englishCsv, column, fileName);
    const chineseTexts = readTexts(chineseCsv, column, fileName);

    for (const [key, english] of englishTexts) {
      const chinese = chineseTexts.get(key);
      if (!english || !chinese) continue;
      const name = english.toLowerCase();
      if (filter && !filter(name)) continue;
      entries.push([name, chinese]);
    }
  }

  // Duplicate English text keeps the last nonempty Chinese translation.
  return Object.fromEntries(entries);
}

